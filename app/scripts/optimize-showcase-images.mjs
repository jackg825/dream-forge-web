/**
 * Generate responsive showcase WebP assets and their TypeScript manifest.
 *
 * Run from any directory: node app/scripts/optimize-showcase-images.mjs
 * Original images remain unchanged. Filenames are derived from encoded bytes,
 * and the manifest has no timestamps so repeated runs produce identical files.
 */

import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const appDirectory = join(dirname(fileURLToPath(import.meta.url)), '..');
const sourceDirectory = join(appDirectory, 'public/showcase');
const outputDirectory = join(sourceDirectory, 'optimized');
const manifestPath = join(appDirectory, 'src/config/showcase-images.ts');
const webpOptions = { quality: 82, effort: 4 };

const images = [
  {
    id: 'racecarRender',
    filename: 'race_car_render.png',
    outputName: 'racecar-render',
    widths: [650, 1300, 2240],
  },
  {
    id: 'racecarOrigin',
    filename: 'race_car_origin.jpg',
    outputName: 'racecar-origin',
    widths: [168, 650, 1300, 2240],
  },
];

async function writeIfChanged(path, content) {
  const bytes = Buffer.isBuffer(content) ? content : Buffer.from(content);

  try {
    if ((await readFile(path)).equals(bytes)) return;
  } catch (error) {
    if (error.code !== 'ENOENT') throw error;
  }

  await writeFile(path, bytes);
}

async function main() {
  await mkdir(outputDirectory, { recursive: true });
  const manifest = {};

  for (const image of images) {
    const source = await readFile(join(sourceDirectory, image.filename));
    const metadata = await sharp(source).metadata();

    if (!metadata.width || !metadata.height) {
      throw new Error(`Cannot determine dimensions for ${image.filename}`);
    }

    const variants = [];

    for (const width of image.widths) {
      if (width > metadata.width) {
        throw new Error(`${image.filename} is smaller than the requested ${width}px variant`);
      }

      const encoded = await sharp(source)
        .resize({ width, withoutEnlargement: true })
        .webp(webpOptions)
        .toBuffer();
      const hash = createHash('sha256').update(encoded).digest('hex').slice(0, 12);
      const filename = `${image.outputName}-${width}.${hash}.webp`;

      await writeIfChanged(join(outputDirectory, filename), encoded);
      variants.push({ src: `/showcase/optimized/${filename}`, width, bytes: encoded.length });
      console.log(`${filename}: ${encoded.length.toLocaleString('en-US')} bytes`);
    }

    const blur = await sharp(source)
      .resize({ width: 16, withoutEnlargement: true })
      .webp({ quality: 45, effort: 4 })
      .toBuffer();

    manifest[image.id] = {
      src: variants.find((variant) => variant.width === 1300).src,
      srcSet: variants.map((variant) => `${variant.src} ${variant.width}w`).join(', '),
      width: metadata.width,
      height: metadata.height,
      blurDataURL: `data:image/webp;base64,${blur.toString('base64')}`,
      variants,
    };
  }

  const source = `// Generated by scripts/optimize-showcase-images.mjs. Do not edit manually.\n\nexport const showcaseImages = ${JSON.stringify(manifest, null, 2)} as const;\n`;
  await writeIfChanged(manifestPath, source);
  console.log('Generated src/config/showcase-images.ts');
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
